export type PixelIconName = keyof typeof ICONS_10;

/** Ícones de interface (setas, fechar, mais...) usam o tamanho pequeno abaixo de 16px. */
const SIMPLE_ICONS: ReadonlySet<string> = new Set([
	"chev",
	"chevd",
	"back",
	"x",
	"plus",
	"minus",
	"menu",
]);

type Grid = readonly string[];

/** Converte a grade em um path SVG: um retângulo por sequência horizontal de pixels. */
export function buildPixelPath(rows: Grid): string {
	let d = "";
	rows.forEach((row, y) => {
		let x = 0;
		while (x < row.length) {
			if (row[x] !== "#") {
				x++;
				continue;
			}
			let end = x;
			while (end + 1 < row.length && row[end + 1] === "#") end++;
			const w = end - x + 1;
			d += `M${x} ${y}h${w}v1h-${w}z`;
			x = end + 1;
		}
	});
	return d;
}

export interface ResolvedPixelIcon {
	/** Lado da grade lógica (viewBox). */
	grid: 8 | 10;
	/** Lado renderizado em px (largura e altura do SVG). */
	px: 10 | 16 | 20;
	path: string;
}

function has8(name: string): name is keyof typeof ICONS_8 {
	return name in ICONS_8;
}

function pickPx(name: string, size: number): 10 | 20 {
	const big = SIMPLE_ICONS.has(name) ? size >= 16 : size >= 12;
	return big ? 20 : 10;
}

const PATH_CACHE = new Map<string, string>();

function cachedPath(key: string, rows: Grid): string {
	const hit = PATH_CACHE.get(key);
	if (hit !== undefined) return hit;
	const built = buildPixelPath(rows);
	PATH_CACHE.set(key, built);
	return built;
}

/**
 * Escolhe a grade e o tamanho final do ícone.
 * - 12–15px com versão 8x8: SVG de 16px (pixel de 2px) — botões, chips, rail.
 * - ≥16px (ou ≥12 sem versão 8x8): 20px — linhas de lista e estados grandes.
 * - ícones simples abaixo de 16px: 10px.
 */
export function resolvePixelIcon(name: PixelIconName, size = 16): ResolvedPixelIcon {
	if (size < 16 && size >= 12 && has8(name)) {
		return { grid: 8, px: 16, path: cachedPath(`8:${name}`, ICONS_8[name]) };
	}
	return { grid: 10, px: pickPx(name, size), path: cachedPath(`10:${name}`, ICONS_10[name]) };
}
